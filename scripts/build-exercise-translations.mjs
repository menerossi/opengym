#!/usr/bin/env node
/* Build the committed runtime packs from a reviewed exercise translation source.
 *
 *   node scripts/build-exercise-translations.mjs
 *   node scripts/build-exercise-translations.mjs --check
 *
 * IDs and English text remain canonical in exercises-data.js. The source below contains only
 * locale-owned display text, so translating an exercise can never invalidate saved routines.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const locale = 'pt-BR';
const sourceFile = join(root, 'translations', 'exercises', `${locale}.json`);
const namesFile = join(root, 'frontend', 'src', 'names', `${locale}.js`);
const instrFile = join(root, 'frontend', 'src', 'instr', `${locale}.js`);
const { EXDB } = await import(pathToFileURL(join(root, 'frontend', 'src', 'lib', 'exercises-data.js')).href);
const source = JSON.parse(readFileSync(sourceFile, 'utf8'));
const translated = source.exercises || {};
const expectedIds = new Set(EXDB.map(ex => ex.id));
const actualIds = Object.keys(translated);
const errors = [];

for (const id of actualIds) if (!expectedIds.has(id)) errors.push(`unknown exercise id ${id}`);
for (const ex of EXDB) {
  const item = translated[ex.id];
  if (!item) { errors.push(`missing exercise ${ex.id}`); continue; }
  if (typeof item.name !== 'string' || !item.name.trim()) errors.push(`${ex.id}: missing name`);
  if (!Array.isArray(item.steps)) errors.push(`${ex.id}: steps must be an array`);
  else {
    if (item.steps.length !== ex.st.length) errors.push(`${ex.id}: expected ${ex.st.length} steps, got ${item.steps.length}`);
    item.steps.forEach((step, i) => {
      if (typeof step !== 'string' || !step.trim()) errors.push(`${ex.id}: empty step ${i + 1}`);
    });
  }
}
if (errors.length) {
  console.error(errors.slice(0, 40).join('\n'));
  if (errors.length > 40) console.error(`…and ${errors.length - 40} more`);
  process.exit(1);
}

const names = Object.fromEntries(EXDB.map(ex => [ex.id, translated[ex.id].name.trim()]));
const instructions = Object.fromEntries(EXDB.map(ex => [ex.id, translated[ex.id].steps.map(s => s.trim())]));
const header = '// generated by scripts/build-exercise-translations.mjs — do not edit\nexport default ';
const outputs = [
  [namesFile, header + JSON.stringify(names) + '\n'],
  [instrFile, header + JSON.stringify(instructions) + '\n']
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [file, content] of outputs) {
    let current = null;
    try { current = readFileSync(file, 'utf8'); } catch { /* missing is stale */ }
    if (current !== content) { console.error(`${file} is out of date`); stale = true; }
  }
  if (stale) process.exit(1);
} else {
  for (const [file, content] of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}

const stepCount = EXDB.reduce((n, ex) => n + ex.st.length, 0);
console.log(`${locale}: ${EXDB.length} names and ${stepCount} instruction steps in sync.`);
